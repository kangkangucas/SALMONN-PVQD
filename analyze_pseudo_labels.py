#!/usr/bin/env python3
"""
Analyze and validate pseudo labels generated by infer_pseudo_labels.py

Usage:
    python analyze_pseudo_labels.py --csv-path results/pseudo_labels.csv
"""

import argparse
import csv
import numpy as np
import pandas as pd
from pathlib import Path
from collections import defaultdict


def parse_args():
    parser = argparse.ArgumentParser(description='Analyze pseudo labels')
    parser.add_argument("--csv-path", type=str, required=True,
                        help='Path to CSV file with pseudo labels')
    parser.add_argument("--output-report", type=str, default=None,
                        help='Path to save analysis report')
    return parser.parse_args()


def analyze_csv(csv_path):
    """Analyze pseudo labels CSV file."""
    
    print("=" * 80)
    print("Pseudo Labels Analysis Report")
    print("=" * 80)
    print()
    
    # Read CSV
    try:
        df = pd.read_csv(csv_path)
    except Exception as e:
        print(f"Error reading CSV: {e}")
        return
    
    print(f"CSV File: {csv_path}")
    print(f"Total rows: {len(df)}")
    print()
    
    # Count successful and failed
    successful = df[df['error'].isna() | (df['error'] == '')].shape[0]
    failed = df[~(df['error'].isna() | (df['error'] == ''))].shape[0]
    
    print("Processing Status:")
    print(f"  ✓ Successful: {successful} ({100*successful/len(df):.1f}%)")
    print(f"  ✗ Failed: {failed} ({100*failed/len(df):.1f}%)")
    print()
    
    # Analyze each task
    tasks = ['breathiness', 'roughness', 'strain']
    
    print("Score Statistics:")
    print("-" * 80)
    
    for task in tasks:
        # Get valid scores
        scores = pd.to_numeric(df[task], errors='coerce')
        valid_scores = scores.dropna()
        
        if len(valid_scores) > 0:
            print(f"\n{task.upper()}:")
            print(f"  Valid scores: {len(valid_scores)}/{len(df)} ({100*len(valid_scores)/len(df):.1f}%)")
            print(f"  Mean: {valid_scores.mean():.2f}")
            print(f"  Std:  {valid_scores.std():.2f}")
            print(f"  Min:  {valid_scores.min():.2f}")
            print(f"  Max:  {valid_scores.max():.2f}")
            print(f"  Median: {valid_scores.median():.2f}")
            
            # Distribution
            print(f"  Distribution:")
            for percentile in [25, 50, 75]:
                val = valid_scores.quantile(percentile / 100)
                print(f"    {percentile}th percentile: {val:.2f}")
        else:
            print(f"\n{task.upper()}: No valid scores")
    
    print()
    print("-" * 80)
    
    # Error analysis
    if failed > 0:
        print("\nError Analysis:")
        print("-" * 80)
        
        error_counts = defaultdict(int)
        for error in df[df['error'].notna()]['error']:
            if error and error != '':
                # Extract error type
                error_type = str(error).split(':')[0]
                error_counts[error_type] += 1
        
        for error_type, count in sorted(error_counts.items(), key=lambda x: -x[1]):
            print(f"  {error_type}: {count}")
    
    print()
    print("=" * 80)
    
    # Return statistics
    return {
        'total': len(df),
        'successful': successful,
        'failed': failed,
        'tasks': {task: {
            'valid': len(pd.to_numeric(df[task], errors='coerce').dropna()),
            'mean': pd.to_numeric(df[task], errors='coerce').mean(),
            'std': pd.to_numeric(df[task], errors='coerce').std(),
        } for task in tasks}
    }


def main():
    args = parse_args()
    
    stats = analyze_csv(args.csv_path)
    
    # Save report if requested
    if args.output_report:
        with open(args.output_report, 'w') as f:
            f.write("Pseudo Labels Analysis Report\n")
            f.write("=" * 80 + "\n\n")
            f.write(f"CSV File: {args.csv_path}\n")
            f.write(f"Total rows: {stats['total']}\n")
            f.write(f"Successful: {stats['successful']}\n")
            f.write(f"Failed: {stats['failed']}\n\n")
            
            for task, task_stats in stats['tasks'].items():
                f.write(f"{task.upper()}:\n")
                f.write(f"  Valid: {task_stats['valid']}\n")
                f.write(f"  Mean: {task_stats['mean']:.2f}\n")
                f.write(f"  Std: {task_stats['std']:.2f}\n\n")
        
        print(f"Report saved to: {args.output_report}")


if __name__ == "__main__":
    main()

